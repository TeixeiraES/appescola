  @override
  void setState(VoidCallback callback) {
    super.setState(callback);
    _model.onUpdate();
  }

  @override
  void initState() {
    super.initState();
    _model = createModel(context, () => RespostaTextFieldModel());

    // On component load action.
    SchedulerBinding.instance.addPostFrameCallback((_) async {
      if (FFAppState().presenceValues.elementAtOrNull(widget.indexParam!) !=
              null &&
          FFAppState().presenceValues.elementAtOrNull(widget.indexParam!) !=
              '') {
        FFAppState().updateDiaryResponseValuesAtIndex(
          widget.indexParam!,
          (e) => e
            ..idPergunta = widget.idPergunta
            ..resposta = widget.respostaParam,
        );
        safeSetState(() {});
      } else {
        FFAppState().addToDiaryResponseValues(RespostaDiarioStruct(
          idPergunta: widget.idPergunta,
          resposta: widget.respostaParam,
        ));
        safeSetState(() {});
      }
    });

    _model.textController ??= TextEditingController();
    _model.textFieldFocusNode ??= FocusNode();

    WidgetsBinding.instance.addPostFrameCallback((_) => safeSetState(() {}));
  }

